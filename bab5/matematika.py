"""Modul matematika sederhana buatan sendiri."""

PI = 3.14159


def tambah(a, b):
    """Mengembalikan hasil a + b."""
    return a + b


def kali(a, b):
    """Mengembalikan hasil a * b."""
    return a * b


def luas_lingkaran(r):
    """Mengembalikan luas lingkaran dengan jari-jari r."""
    return PI * r ** 2
